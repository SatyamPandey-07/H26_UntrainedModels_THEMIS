import { existsSync, readdirSync, readFileSync } from "node:fs";
import { dirname, join, normalize, relative } from "node:path";
import { normalizePythonName } from "./names.js";

export interface RequirementEntry {
  /** PEP 503 normalised name. */
  name: string;
  rawName: string;
  /** "" or "[extra1,extra2]". */
  extras: string;
  /** ">=1.0,<2", "==1.2.3" or "". */
  specifier: string;
  marker: string;
  /** sha256 hashes from `--hash=` options. */
  hashes: string[];
  comment: string;
  file: string;
  /** 1-based first physical line of the (possibly continued) requirement. */
  line: number;
  endLine: number;
}

export interface SkippedRequirement {
  file: string;
  line: number;
  text: string;
  reason: string;
}

export interface RequirementsFile {
  path: string;
  entries: RequirementEntry[];
  includes: string[];
  skipped: SkippedRequirement[];
  hasHashes: boolean;
  /** Header says the file was generated by pip-compile. */
  pipCompiled: boolean;
}

const NAME_LINE = /^([A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?)\s*(\[[^\]]*\])?\s*([^;]*?)\s*(?:;\s*(.*))?$/;

function stripComment(text: string): { body: string; comment: string } {
  const m = /(^|\s)#/.exec(text);
  if (!m) return { body: text, comment: "" };
  return { body: text.slice(0, m.index), comment: text.slice(m.index + m[1]!.length) };
}

/** Parses the text of one requirements file. Pure: no file access, so it can be tested on strings. */
export function parseRequirementsText(path: string, text: string): RequirementsFile {
  const physical = text.split(/\r?\n/);
  const entries: RequirementEntry[] = [];
  const includes: string[] = [];
  const skipped: SkippedRequirement[] = [];
  const header = physical.slice(0, 12).join("\n");
  const pipCompiled = /pip-compile|autogenerated by/i.test(header);
  let hasHashes = false;

  for (let i = 0; i < physical.length; i++) {
    const start = i;
    let logical = physical[i] ?? "";
    while (/\\\s*$/.test(logical) && i + 1 < physical.length) {
      logical = logical.replace(/\\\s*$/, " ") + (physical[++i] ?? "");
    }
    const { body, comment } = stripComment(logical);
    const trimmed = body.trim();
    if (!trimmed) continue;
    const line = start + 1;

    const include = /^(?:-r|--requirement)[\s=]+(\S+)/.exec(trimmed);
    if (include) {
      includes.push(include[1] as string);
      continue;
    }
    if (/^(?:-c|--constraint)\b/.test(trimmed)) continue;
    if (/^-/.test(trimmed)) {
      skipped.push({
        file: path,
        line,
        text: trimmed.slice(0, 120),
        reason: "pip option or editable install",
      });
      continue;
    }
    const hashes = [...trimmed.matchAll(/--hash[=\s]+sha256:([0-9a-f]{64})/gi)].map((m) => m[1] as string);
    if (hashes.length > 0 || /--hash/.test(trimmed)) hasHashes = true;
    const spec = trimmed.replace(/\s--[A-Za-z-]+(?:[=\s]+\S+)?/g, "").trim();
    if (/\s@\s|:\/\/|^git\+|^\.|^\//.test(spec)) {
      skipped.push({
        file: path,
        line,
        text: spec.slice(0, 120),
        reason: "URL, VCS or local-path requirement",
      });
      continue;
    }
    const m = NAME_LINE.exec(spec);
    if (!m) {
      skipped.push({ file: path, line, text: spec.slice(0, 120), reason: "unparseable requirement line" });
      continue;
    }
    entries.push({
      name: normalizePythonName(m[1] as string),
      rawName: m[1] as string,
      extras: m[2] ?? "",
      specifier: (m[3] ?? "").replace(/\s+/g, ""),
      marker: (m[4] ?? "").trim(),
      hashes,
      comment,
      file: path,
      line,
      endLine: i + 1,
    });
  }
  return { path, entries, includes, skipped, hasHashes, pipCompiled };
}

const REQ_FILE = /^(?:[\w.-]*requirements[\w.-]*)\.txt$/i;

/** Requirements files at the repository root and in `requirements/`, relative to `repoPath`. */
export function discoverRequirementsFiles(repoPath: string): string[] {
  const out: string[] = [];
  const scan = (dir: string, anyTxt: boolean) => {
    const abs = join(repoPath, dir);
    if (!existsSync(abs)) return;
    for (const name of readdirSync(abs).sort()) {
      if (anyTxt ? /\.txt$/i.test(name) : REQ_FILE.test(name)) out.push(dir ? `${dir}/${name}` : name);
    }
  };
  scan("", false);
  scan("requirements", true);
  // The plain requirements.txt is the primary manifest; the rest keep their alphabetical order.
  return out.sort((a, b) => Number(b === "requirements.txt") - Number(a === "requirements.txt"));
}

export function isDevRequirementsFile(path: string): boolean {
  return /(^|[/_.-])(dev|test|tests|lint|ci|docs?|typing|style|mypy)([/_.-]|$)/i.test(path);
}

export interface RequirementsGraph {
  files: RequirementsFile[];
  entries: RequirementEntry[];
  skipped: SkippedRequirement[];
}

/** Reads every requirements file plus anything they `-r` include. */
export function readRequirements(repoPath: string): RequirementsGraph {
  const files: RequirementsFile[] = [];
  const seen = new Set<string>();
  const queue = discoverRequirementsFiles(repoPath);
  while (queue.length > 0) {
    const rel = queue.shift() as string;
    if (seen.has(rel)) continue;
    seen.add(rel);
    const abs = join(repoPath, rel);
    if (!existsSync(abs)) continue;
    const parsed = parseRequirementsText(rel, readFileSync(abs, "utf8"));
    files.push(parsed);
    for (const inc of parsed.includes) {
      const target = normalize(join(dirname(rel), inc));
      if (!target.startsWith("..") && !queue.includes(target)) queue.push(relative(".", target));
    }
  }
  return {
    files,
    entries: files.flatMap((f) => f.entries),
    skipped: files.flatMap((f) => f.skipped),
  };
}

/** Exact version from `==`/`===` (no wildcard), else undefined. */
export function pinnedVersion(specifier: string): string | undefined {
  const m = /(?:^|,)===?([0-9A-Za-z.+!_-]+)(?:,|$)/.exec(specifier);
  return m && !m[1]!.includes("*") ? m[1] : undefined;
}

/** Lower bound from `>=`, `~=` or `>`, used as the "installed" version when nothing is pinned. */
export function lowerBound(specifier: string): string | undefined {
  const m = /(?:>=|~=|>)([0-9][0-9A-Za-z.+!_-]*)/.exec(specifier);
  return m?.[1];
}
